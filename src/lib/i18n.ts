export const DICTIONARIES: Record<Lang, Dict> = { en, es };

export function dict(lang: Lang): Dict {
  return DICTIONARIES[lang] ?? en;
}

/** Label of an option value in a language; falls back to the raw value. */
export function optionLabel(lang: Lang, value: string): string {
  return dict(lang).options[value] ?? value;
}
